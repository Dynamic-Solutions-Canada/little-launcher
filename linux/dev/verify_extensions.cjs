'use strict';
const assert=require('node:assert/strict');
const {app}=require('electron');
const fs=require('node:fs'),path=require('node:path'),http=require('node:http');
assert.equal(process.env.XDG_RUNTIME_DIR,'/tmp/ll-runtime');
const root=fs.mkdtempSync('/work/extensions-qa-');app.setPath('userData',root);
const browserRoot=process.env.LL_BROWSER_ROOT||path.resolve(__dirname,'../browser');
const {ExtensionHost}=require(path.join(browserRoot,'extension_host.cjs'));
const {WebLauncher}=require(path.join(browserRoot,'window.cjs'));
const {Profiles}=require(path.join(browserRoot,'profiles.cjs'));
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let owner,server,host;
app.whenReady().then(async()=>{
 const records=[];const services={isQuitting:()=>true,request:async()=>false,emit:record=>records.push(record)};
 host=new ExtensionHost(services.emit);services.extensions=host;host.changed=()=>owner?.toolbar();
 services.profiles=new Profiles(services.request,contents=>owner?.tabs.some(tab=>tab.view?.webContents===contents)?owner:null);services.profiles.extensions=host;
 const name=fs.readFileSync('/source/.artifacts/linux-native/extension-qualification/bitwarden-path','utf8').trim();
 const source=name.replace('/development/little-launcher','/source');
 const installed=path.join(root,'extensions/packages/bitwarden');fs.mkdirSync(path.dirname(installed),{recursive:true});fs.cpSync(source,installed,{recursive:true});
 const config={Id:'extensions-a',Kind:1,Name:'Extension fixture',WebHiddenPolicy:2};
 const profile=services.profiles.get(config);
 const entries=await host.command({action:'add',path:installed},profile,null);
 assert.equal(entries.length,1);assert.equal(entries[0].version,'2026.10.1');assert.equal(entries[0].running,true);
 console.log('Bitwarden background host ready');
 server=http.createServer((req,res)=>{res.setHeader('Content-Type','text/html');res.end('<title>Extension fixture</title><form><input name=username autocomplete=username><input name=password type=password autocomplete=current-password></form>');});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 owner=new WebLauncher(config,{window:'#eff0f1',text:'#232629',button:'#dddddd',highlight:'#3daee9',font:'Noto Sans',fontSize:10},null,{homeUrl:`http://127.0.0.1:${server.address().port}/`,showBookmarkBar:false},services);
 owner.show();for(let i=0;i<150&&owner.view.webContents.isLoading();i++)await delay(50);await delay(1500);
 const chrome=owner.window.webContents;
 await host.command({action:'pin',id:entries[0].id,pinned:true},profile,owner);await delay(200);
 assert.equal(await chrome.executeJavaScript('document.getElementById("extensions").hidden'),false);
 assert.equal(await chrome.executeJavaScript('document.querySelectorAll("#pinned-extensions button img").length'),1);
 assert.equal(new ExtensionHost(()=>{}).entries[0].pinned,true,'Pin choice persists in local catalog');
 const menu=host.menu(owner);assert.equal(menu[0].submenu[1].label,'Pin to the header');assert.equal(menu[0].submenu[1].checked,true);
 const order=await chrome.executeJavaScript('Array.from(document.querySelector("#more").parentElement.children).map(node=>node.id)');
 assert.ok(order.indexOf('extensions')===order.indexOf('more')+1 && order.indexOf('pinned-extensions')===order.indexOf('extensions')+1);
 assert.equal(await owner.view.webContents.executeJavaScript('typeof require+":"+typeof window.launcher'),'undefined:undefined');
 const {ipcMain}=require('electron');
 ipcMain.on('toolbar-action',(event,action,value)=>owner.handleToolbar(event,action,value));
 await chrome.executeJavaScript('document.querySelector("#pinned-extensions button").click()');await delay(2000);
 const {BrowserWindow}=require('electron');const popup=BrowserWindow.getAllWindows().find(window=>window!==owner.window&&window.webContents.getURL().startsWith('chrome-extension:'));
 assert.ok(popup,'Bitwarden extension popup opened');
 const text=await popup.webContents.executeJavaScript('document.body.innerText');
 assert.ok(text.length>30 && /email|log in|sign in|account/i.test(text),'Bitwarden login UI rendered');
 fs.writeFileSync('/work/extension-popup.png',(await popup.webContents.capturePage()).toPNG());
 fs.writeFileSync('/work/extension-toolbar.png',(await chrome.capturePage()).toPNG());
 const fido=await owner.view.webContents.executeJavaScript('({get:navigator.credentials.get.toString().includes("[native code]"),create:navigator.credentials.create.toString().includes("[native code]")})');
 console.log('Bitwarden page credential methods: '+JSON.stringify(fido));
 await popup.webContents.executeJavaScript('chrome.storage.local.set({littleLauncherFixture:"profile-a"})');
 const second=services.profiles.get({Id:'extensions-b',Kind:1});await host.register(second);
 const extension=second.extensions.getAllExtensions().find(item=>item.path===installed);assert.ok(extension);
 const other=new BrowserWindow({show:false,webPreferences:{session:second,sandbox:true,contextIsolation:true,nodeIntegration:false}});
 await other.loadURL(`chrome-extension://${extension.id}/popup/index.html`);
 const isolated=await other.webContents.executeJavaScript('chrome.storage.local.get("littleLauncherFixture")');
 assert.equal(isolated.littleLauncherFixture,undefined);other.destroy();
 await host.command({action:'enable',path:installed,enabled:false},profile,owner);
 assert.equal(profile.extensions.getAllExtensions().length,0);assert.equal(second.extensions.getAllExtensions().length,0);assert.ok(popup.isDestroyed());
 await host.command({action:'pin',id:entries[0].id,pinned:false},profile,owner);await delay(100);
 assert.equal(await chrome.executeJavaScript('document.querySelectorAll("#pinned-extensions button").length'),0);
 console.log(JSON.stringify({extensionToolbar:true,pinPersists:true,passed:true,actualBitwarden:true,backgroundStorageReady:true,popupRenders:true,profileStorageIsolated:true,disableClosesPopups:true,remoteBridgeAbsent:true,extensionVersion:entries[0].version,accountUsed:false,passkeyVaultAcceptancePending:true}));
 fs.writeFileSync('/work/extension-result.json',JSON.stringify({passed:true,actualBitwarden:true,popupTextLength:text.length,extensionVersion:entries[0].version,root}));
}).catch(error=>{console.error(error.stack);process.exitCode=1;}).finally(()=>{
 if(owner){for(const tab of owner.tabs){tab.closing=true;tab.view?.webContents.close({waitForBeforeUnload:false});}owner.window.destroy();}
 for(const state of host?.sessions.values()||[])state.compat.disposeStorageObservers();
 server?.close();app.exit(process.exitCode||0);
});
