"""Native Cloud Sync page following the Windows provider/card/section layout."""
from PySide6.QtCore import Qt, QTimer
from PySide6.QtGui import QIcon
from PySide6.QtWidgets import (QCheckBox, QFrame, QHBoxLayout, QLabel, QPushButton,
    QScrollArea, QSizePolicy, QSpinBox, QToolButton, QVBoxLayout, QWidget)
from .launcher_card import LauncherCard
from .item_toolbar import ActionFlowLayout
from .launcher_settings import SettingsRow, text_label


class Destination(LauncherCard):
    def __init__(self, title, status, icon, supported=True, parent=None):
        super().__init__(parent)
        self.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Maximum)
        layout = QVBoxLayout(self)
        layout.setContentsMargins(16, 12, 16, 16)
        layout.setSpacing(8)
        header = QHBoxLayout()
        header.setSpacing(12)
        image = QLabel()
        image.setPixmap(QIcon.fromTheme(icon).pixmap(20, 20))
        image.setFixedSize(20, 20)
        header.addWidget(image)
        labels = QWidget()
        labels.setSizePolicy(QSizePolicy.Ignored, QSizePolicy.Preferred)
        text = QVBoxLayout(labels)
        text.setContentsMargins(0, 0, 0, 0)
        text.setSpacing(0)
        text.addWidget(text_label(title))
        self.status = text_label(status, 12, True)
        text.addWidget(self.status)
        header.addWidget(labels, 1)
        self.enabled = QCheckBox()
        self.enabled.setAccessibleName('Enable ' + title)
        self.enabled.setEnabled(supported)
        header.addWidget(self.enabled)
        self.expand = QToolButton()
        self.expand.setAutoRaise(True)
        self.expand.setCheckable(True)
        self.expand.setChecked(False)
        self.expand.setArrowType(Qt.RightArrow)
        self.expand.setAccessibleName('Expand ' + title)
        header.addWidget(self.expand)
        layout.addLayout(header)
        self.body = QWidget()
        self.content = QVBoxLayout(self.body)
        self.content.setContentsMargins(0, 4, 0, 0)
        self.content.setSpacing(8)
        layout.addWidget(self.body)
        self.body.setVisible(False)
        self.expand.toggled.connect(self._expanded)

    def _expanded(self, expanded):
        self.body.setVisible(expanded)
        self.expand.setArrowType(Qt.DownArrow if expanded else Qt.RightArrow)


class CloudSyncPage(QWidget):
    def __init__(self, sync, download, upload, import_file, export_file, parent=None):
        super().__init__(parent)
        self.sync = sync
        outer = QVBoxLayout(self)
        outer.setContentsMargins(0, 0, 0, 0)
        scroll = QScrollArea()
        scroll.setFrameShape(QFrame.NoFrame)
        scroll.setWidgetResizable(True)
        body = QWidget()
        body.setMaximumWidth(1000)
        layout = QVBoxLayout(body)
        layout.setContentsMargins(16, 16, 16, 16)
        layout.setSpacing(4)
        title = text_label('Cloud Sync', 24)
        font = title.font(); font.setBold(True); title.setFont(font)
        layout.addWidget(title)
        layout.addSpacing(4)
        layout.addWidget(text_label('Keep your launchers in sync across machines, through OneDrive, Google Drive, WebDAV, a folder or network share, or your own SSH/SFTP server.', 14, True))
        layout.addSpacing(12)
        layout.addWidget(text_label('Destinations'))
        layout.addWidget(text_label('OneDrive is available in this Linux preview. Other destinations are shown below and are not available yet.', 12, True))
        layout.addSpacing(4)
        self.onedrive = Destination('OneDrive', '', 'folder-cloud')
        self.onedrive.enabled.setChecked(sync.state.get('Enabled', True))
        self.onedrive.enabled.toggled.connect(sync.set_enabled)
        self.hint = text_label('', 12, True)
        self.onedrive.content.addWidget(self.hint)
        accounts = QHBoxLayout()
        accounts.setSpacing(8)
        self.sign_in = QPushButton('Sign in…')
        self.sign_in.clicked.connect(sync.sign_in)
        self.sign_out = QPushButton('Sign out')
        self.sign_out.clicked.connect(sync.sign_out)
        self.cancel = QPushButton('Cancel sign-in')
        self.cancel.clicked.connect(sync.cancel)
        accounts.addWidget(self.sign_in)
        accounts.addWidget(self.sign_out)
        accounts.addWidget(self.cancel)
        accounts.addStretch()
        self.onedrive.content.addLayout(accounts)
        layout.addWidget(self.onedrive)
        for name, icon in [('Google Drive', 'folder-cloud'), ('WebDAV (Nextcloud, ownCloud…)', 'network-server'),
                           ('Folder or network share', 'folder-network'), ('SSH / SFTP server', 'network-server')]:
            destination = Destination(name, 'Not available in this build', icon, supported=False)
            destination.content.addWidget(text_label('This destination is not implemented on Linux yet.', 12, True))
            layout.addWidget(destination)
        layout.addSpacing(12)
        layout.addWidget(text_label('Automatic Sync'))
        self.automatic = QCheckBox()
        self.automatic.setChecked(sync.state.get('Automatic', False))
        self.automatic.toggled.connect(self._automatic)
        self.automatic_row = self._row(layout, 'Auto Sync', 'Sync launcher items on startup, on change, and periodically', self.automatic)
        self.interval = QSpinBox()
        self.interval.setRange(1, 1440)
        self.interval.setFixedWidth(140)
        self.interval.setValue(sync.state.get('IntervalMinutes', 5))
        self.interval.valueChanged.connect(sync.set_interval)
        self._row(layout, 'Sync Interval (minutes)', 'How often to download launcher items', self.interval)
        layout.addSpacing(12)
        layout.addWidget(text_label('Actions'))
        action_body = QWidget()
        actions = ActionFlowLayout(action_body)
        self.test = QPushButton('Test All')
        self.test.clicked.connect(sync.test_connection)
        self.upload = QPushButton('Upload Launchers')
        self.upload.clicked.connect(upload)
        self.download = QPushButton('Download Launchers')
        self.download.clicked.connect(download)
        for button in (self.test, self.upload, self.download): actions.addWidget(button)
        layout.addWidget(action_body)
        self.notice = text_label('', 12)
        self.notice.setTextInteractionFlags(Qt.TextSelectableByMouse)
        layout.addWidget(self.notice)
        layout.addSpacing(12)
        layout.addWidget(text_label('Import and export'))
        local_body = QWidget()
        local = ActionFlowLayout(local_body)
        for label, callback in [('Import launchers…', import_file), ('Export launchers…', export_file)]:
            button = QPushButton(label)
            button.clicked.connect(callback)
            local.addWidget(button)
        layout.addWidget(local_body)
        layout.addStretch()
        scroll.setWidget(body)
        outer.addWidget(scroll)
        sync.account_changed.connect(lambda *_: self.update_state())
        sync.state_changed.connect(self.update_state)
        sync.busy_changed.connect(lambda *_: self.update_state())
        sync.status.connect(self.notice.setText)
        self.update_state()

    @staticmethod
    def _row(layout, title, subtitle, control):
        card = LauncherCard()
        content = QVBoxLayout(card)
        content.setContentsMargins(16, 16, 16, 16)
        row = SettingsRow(title, subtitle, control)
        content.addWidget(row)
        layout.addWidget(card)
        return row

    def _automatic(self, enabled):
        if not self.sync.set_automatic(enabled):
            self.automatic.blockSignals(True)
            self.automatic.setChecked(self.sync.state.get('Automatic', False))
            self.automatic.blockSignals(False)

    def update_state(self):
        busy = self.sync.job is not None
        signed_in = self.sync.signed_in
        self.onedrive.status.setText(self.sync.account_name or ('Connected' if signed_in else 'Not signed in'))
        self.hint.setText("Stored in this app's own OneDrive folder. Nothing else in your drive is visible to it." if signed_in else
                          'Sign in with a personal Microsoft account. The folder destination for work and school accounts is not available on Linux yet.')
        self.sign_in.setVisible(not signed_in)
        self.sign_out.setVisible(signed_in)
        self.sign_in.setEnabled(not busy)
        self.sign_out.setEnabled(not busy)
        self.cancel.setVisible(busy and self.sync.cancellable)
        self.onedrive.enabled.setEnabled(not busy)
        self.onedrive.enabled.blockSignals(True)
        self.onedrive.enabled.setChecked(self.sync.state.get('Enabled', True))
        self.onedrive.enabled.blockSignals(False)
        for button in (self.test, self.upload, self.download):
            button.setEnabled(not busy and signed_in and self.sync.state.get('Enabled', True))
        reason = self.sync.automatic_unavailable_reason()
        self.automatic.setEnabled(not busy and (not reason or self.sync.state.get('Automatic', False)))
        self.automatic.setToolTip(reason or 'Sync on startup, when launchers change, and at the selected interval.')
        self.automatic_row.subtitle.setText(reason or 'Sync launcher items on startup, on change, and periodically')
        self.upload.setEnabled(not busy and not reason)
        self.upload.setToolTip(reason or 'Upload launcher settings to OneDrive')
        self.interval.setEnabled(not busy)
        self.automatic.blockSignals(True)
        self.automatic.setChecked(self.sync.state.get('Automatic', False))
        self.automatic.blockSignals(False)

    def showEvent(self, event):
        super().showEvent(event)
        QTimer.singleShot(0, self.sync.check_account)
